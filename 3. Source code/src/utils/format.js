export const pad=(n,l=2)=>String(n).padStart(l,'0');
const isoD=d=>d.getFullYear()+'-'+pad(d.getMonth()+1)+'-'+pad(d.getDate());
export const today=()=>isoD(new Date());
export const addDays=(iso,n)=>{const d=new Date(iso+'T00:00:00');d.setDate(d.getDate()+n);return isoD(d)};
export const diffDays=(a,b)=>Math.round((new Date(a+'T00:00:00')-new Date(b+'T00:00:00'))/864e5);
export const fD=iso=>iso?iso.slice(8,10)+'/'+iso.slice(5,7)+'/'+iso.slice(0,4):'';
export const fT=dt=>{if(!dt)return'';const d=new Date(dt);const h=d.getHours();return pad(h%12||12)+':'+pad(d.getMinutes())+' '+(h<12?'SA':'CH')};
const fT24=dt=>{if(!dt)return'';const d=new Date(dt);return pad(d.getHours())+':'+pad(d.getMinutes())};
export const fDT=dt=>dt?fD(dt.slice(0,10))+' '+fT24(dt):'';
export const nowISO=()=>{const d=new Date();return isoD(d)+'T'+pad(d.getHours())+':'+pad(d.getMinutes())+':00'};
